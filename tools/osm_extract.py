"""Build map-data.js: roads, rail, parks and building outlines for each trade-area map.

Data comes from OpenStreetMap through the Overpass API (ODbL; slides credit it).
Coordinates are stored as whole metres from each map's top-left corner, so the
page can draw them as SVG without a map library.

    python3 tools/osm_extract.py            # writes map-data.js next to index.html
"""
import json, math, os, sys, time, urllib.parse, urllib.request

# name: (south, west, north, east) — about 1.7 km wide and 0.8 km tall, the slide's map shape
AREAS = {
    'seongsu': (37.5399, 127.0465, 37.5471, 127.0655),
    'sinsa': (37.5164, 127.0130, 37.5236, 127.0320),
    'hannam': (37.5339, 126.9915, 37.5411, 127.0105),
    'myeongdong': (37.5589, 126.9755, 37.5661, 126.9945),
}
ROAD = {'motorway': 3, 'trunk': 3, 'primary': 3, 'secondary': 2, 'tertiary': 2,
        'unclassified': 1, 'residential': 1, 'living_street': 1, 'pedestrian': 1, 'service': 0}
ENDPOINT = 'https://overpass-api.de/api/interpreter'


def query(bbox):
    s, w, n, e = bbox
    b = f'{s},{w},{n},{e}'
    q = f"""[out:json][timeout:60];
(way["highway"~"^({'|'.join(ROAD)})$"]({b});
 way["railway"~"^(subway|rail|light_rail)$"]["tunnel"!="yes"]({b});
 way["leisure"="park"]({b}); way["landuse"="grass"]({b});
 way["building"]({b}););
out geom;"""
    req = urllib.request.Request(ENDPOINT, data=urllib.parse.urlencode({'data': q}).encode(),
                                 headers={'User-Agent': 'leasedesk-prototype/1 (mockup map extract)'})
    with urllib.request.urlopen(req, timeout=120) as r:
        return json.load(r)['elements']


def build(name, bbox):
    s, w, n, e = bbox
    kx = math.cos(math.radians((s + n) / 2)) * 111320
    ky = 110540
    W, H = round((e - w) * kx), round((n - s) * ky)
    xy = lambda p: [round((p['lon'] - w) * kx), round((n - p['lat']) * ky)]
    out = {'bbox': bbox, 'w': W, 'h': H, 'roads': [], 'rail': [], 'parks': [], 'buildings': []}
    for el in query(bbox):
        g = el.get('geometry'); t = el.get('tags', {})
        if not g: continue
        pts = [c for p in g for c in xy(p)]
        if 'building' in t:
            out['buildings'].append([el['id'], pts])
        elif 'railway' in t:
            out['rail'].append(pts)
        elif t.get('leisure') == 'park' or t.get('landuse') == 'grass':
            out['parks'].append(pts)
        elif t.get('highway') in ROAD:
            out['roads'].append([ROAD[t['highway']], pts])
    return out


def main():
    data = {}
    for name, bbox in AREAS.items():
        data[name] = build(name, bbox)
        d = data[name]
        print(f"{name}: {d['w']}x{d['h']} m, roads {len(d['roads'])}, rail {len(d['rail'])}, parks {len(d['parks'])}, buildings {len(d['buildings'])}", file=sys.stderr)
        time.sleep(2)  # be gentle with the public Overpass server
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'map-data.js')
    with open(path, 'w') as f:
        f.write('/* Generated by tools/osm_extract.py — © OpenStreetMap contributors (ODbL). Do not edit. */\n')
        f.write('window.MAP_DATA = ' + json.dumps(data, separators=(',', ':')) + ';\n')
    print(f'wrote {os.path.getsize(path):,} bytes', file=sys.stderr)


if __name__ == '__main__':
    main()
