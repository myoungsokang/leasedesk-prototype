"""Build official-data.js: Seoul's official trade areas (서울시 상권분석서비스 영역-상권) on our four maps.

Source: data.seoul.go.kr OA-15560 (shapefile, EPSG:5181). The polygons are converted to the same whole
metres as map-data.js, so a company zone and an official area can be overlapped directly.
Only names, codes, types and outlines are real; the figures the page shows for them are samples.

    python3 tools/official_extract.py            # downloads, converts, writes official-data.js
"""
import io, json, math, os, struct, sys, urllib.parse, urllib.request, zipfile

MAPS = {'seongsu': (37.5399, 127.0465, 37.5471, 127.0655), 'sinsa': (37.5164, 127.0130, 37.5236, 127.0320),
        'hannam': (37.5339, 126.9915, 37.5411, 127.0105), 'myeongdong': (37.5589, 126.9755, 37.5661, 126.9945)}
URL = 'https://datafile.seoul.go.kr/bigfile/iot/inf/nio_download.do?&useCache=false'


def download():
    body = urllib.parse.urlencode({'infId': 'OA-15560', 'seqNo': '', 'seq': '5', 'infSeq': '3'}).encode()
    req = urllib.request.Request(URL, data=body, headers={'Referer': 'https://data.seoul.go.kr/dataList/OA-15560/S/1/datasetView.do', 'User-Agent': 'leasedesk-prototype/1'})
    z = zipfile.ZipFile(io.BytesIO(urllib.request.urlopen(req, timeout=180).read()))
    return {i.filename.rsplit('.', 1)[-1]: z.read(i) for i in z.infolist()}


def dbf(f):
    n, hlen, rlen = struct.unpack('<IHH', f[4:12]); fields = []
    for i in range(32, hlen - 1, 32):
        fields.append((f[i:i + 11].split(b'\0')[0].decode(), f[i + 16]))
    for r in range(n):
        off, rec = hlen + r * rlen + 1, {}
        for name, ln in fields:
            rec[name] = f[off:off + ln].decode('utf-8', 'replace').strip(); off += ln
        yield rec


def shp(s):
    pos = 100
    while pos < len(s):
        _, clen = struct.unpack('>ii', s[pos:pos + 8]); body = s[pos + 8:pos + 8 + clen * 2]; pos += 8 + clen * 2
        if struct.unpack('<i', body[:4])[0] == 0: yield []; continue
        np_, nv = struct.unpack('<ii', body[36:44]); parts = list(struct.unpack('<%di' % np_, body[44:44 + 4 * np_])) + [nv]
        base = 44 + 4 * np_
        pts = [struct.unpack('<dd', body[base + 16 * k:base + 16 * k + 16]) for k in range(nv)]
        yield [pts[parts[i]:parts[i + 1]] for i in range(np_)]


# EPSG:5181 → WGS84: inverse transverse Mercator on GRS80 (lat0 38°, lon0 127°, k 1, FE 200 000, FN 500 000)
A, F = 6378137.0, 1 / 298.257222101
E2 = F * (2 - F); EP2 = E2 / (1 - E2); E1 = (1 - math.sqrt(1 - E2)) / (1 + math.sqrt(1 - E2))
def _m(p): return A * ((1 - E2 / 4 - 3 * E2**2 / 64 - 5 * E2**3 / 256) * p - (3 * E2 / 8 + 3 * E2**2 / 32 + 45 * E2**3 / 1024) * math.sin(2 * p) + (15 * E2**2 / 256 + 45 * E2**3 / 1024) * math.sin(4 * p) - 35 * E2**3 / 3072 * math.sin(6 * p))
M0 = _m(math.radians(38))
def to_ll(x, y):
    x -= 200000; mu = (M0 + y - 500000) / (A * (1 - E2 / 4 - 3 * E2**2 / 64 - 5 * E2**3 / 256))
    p = mu + (3 * E1 / 2 - 27 * E1**3 / 32) * math.sin(2 * mu) + (21 * E1**2 / 16 - 55 * E1**4 / 32) * math.sin(4 * mu) + 151 * E1**3 / 96 * math.sin(6 * mu) + 1097 * E1**4 / 512 * math.sin(8 * mu)
    c, t = EP2 * math.cos(p)**2, math.tan(p)**2; n = A / math.sqrt(1 - E2 * math.sin(p)**2); r = A * (1 - E2) / (1 - E2 * math.sin(p)**2)**1.5; d = x / n
    lat = p - n * math.tan(p) / r * (d**2 / 2 - (5 + 3 * t + 10 * c - 4 * c**2 - 9 * EP2) * d**4 / 24 + (61 + 90 * t + 298 * c + 45 * t**2 - 252 * EP2 - 3 * c**2) * d**6 / 720)
    lon = math.radians(127) + (d - (1 + 2 * t + c) * d**3 / 6 + (5 - 2 * c + 28 * t - 3 * c**2 + 8 * EP2 + 24 * t**2) * d**5 / 120) / math.cos(p)
    return math.degrees(lat), math.degrees(lon)


def main():
    files = download(); out = []
    for rec, rings in zip(dbf(files['dbf']), shp(files['shp'])):
        if not rings: continue
        ring = [to_ll(x, y) for x, y in max(rings, key=len)]
        lats, lons = [p[0] for p in ring], [p[1] for p in ring]
        for key, (s, w, n, e) in MAPS.items():
            if max(lats) < s or min(lats) > n or max(lons) < w or min(lons) > e: continue
            kx = math.cos(math.radians((s + n) / 2)) * 111320; poly = []
            for la, lo in ring:
                p = [round((lo - w) * kx), round((n - la) * 110540)]
                if not poly or p != poly[-1]: poly.append(p)
            out.append({'code': rec['TRDAR_CD'], 'type': rec['TRDAR_SE_C'], 'name': rec['TRDAR_CD_N'], 'gu': rec['SIGNGU_CD_'], 'dong': rec['ADSTRD_CD_'],
                        'area': round(float(rec['RELM_AR'] or 0)), 'osm': key, 'poly': poly})
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'official-data.js')
    with open(path, 'w') as f:
        f.write('/* Generated by tools/official_extract.py from 서울시 상권분석서비스(영역-상권), data.seoul.go.kr OA-15560. Do not edit. */\n')
        f.write('window.OFFICIAL_AREAS = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
    print(f'{len(out)} areas on {len(MAPS)} maps, {os.path.getsize(path):,} bytes', file=sys.stderr)


if __name__ == '__main__':
    main()
